export const AIRLINES: Airline[] = raw.map(([code, name]) => ({ code, name }));

export function searchAirlines(q: string, limit = 10): Airline[] {
  const lower = q.toLowerCase().trim();
  if (!lower) return AIRLINES.slice(0, limit);
  return AIRLINES.filter(
    (a) =>
      a.name.toLowerCase().includes(lower) ||
      a.code.toLowerCase() === lower ||
      a.code.toLowerCase().startsWith(lower)
  ).slice(0, limit);
}
