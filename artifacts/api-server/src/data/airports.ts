export const AIRPORTS: Airport[] = raw.map(([iata, name, city, country]) => ({
  iata,
  name,
  city,
  country,
}));

export function searchAirports(q: string, limit = 10): Airport[] {
  const lower = q.toLowerCase().trim();
  if (!lower || lower.length < 1) return [];
  return AIRPORTS.filter(
    (a) =>
      a.iata.toLowerCase().startsWith(lower) ||
      a.city.toLowerCase().startsWith(lower) ||
      a.city.toLowerCase().includes(lower) ||
      a.name.toLowerCase().includes(lower) ||
      a.country.toLowerCase() === lower
  )
    .sort((a, b) => {
      // Exact IATA match first
      const aExact = a.iata.toLowerCase() === lower ? 0 : 1;
      const bExact = b.iata.toLowerCase() === lower ? 0 : 1;
      if (aExact !== bExact) return aExact - bExact;
      // City starts-with next
      const aCity = a.city.toLowerCase().startsWith(lower) ? 0 : 1;
      const bCity = b.city.toLowerCase().startsWith(lower) ? 0 : 1;
      return aCity - bCity;
    })
    .slice(0, limit);
}
